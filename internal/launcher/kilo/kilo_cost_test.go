package kilo

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// The plugin has to reach Kilo's process, and the only place Kilo learns about
// a plugin file is the config it is handed. A launch without one must still
// produce a valid config.
func TestInlineConfigDeclaresTheCostPluginOnlyWhenOneIsWritten(t *testing.T) {
	const url = "file:///tmp/prizmal/kilo/plugin/prizmal_cost.ts"

	raw, err := buildInlineConfigFor("", "smart", nil, url)
	if err != nil {
		t.Fatalf("buildInlineConfigFor with a plugin: %v", err)
	}
	if !strings.Contains(raw, `"plugin"`) || !strings.Contains(raw, url) {
		t.Fatalf("config does not declare the cost plugin %q: %s", url, raw)
	}

	raw, err = buildInlineConfigFor("", "smart", nil, "")
	if err != nil {
		t.Fatalf("buildInlineConfigFor without a plugin: %v", err)
	}
	if strings.Contains(raw, `"plugin"`) {
		t.Fatalf("config declares a plugin when none was written: %s", raw)
	}
}

// Kilo loads a plugin by file path, so the file has to exist where the config
// says it does, and a rewrite has to be visible in its contents.
func TestWriteKiloCostPluginWritesTheFileAndReturnsItsURL(t *testing.T) {
	dir := t.TempDir()

	url, err := writeKiloCostPlugin(dir)
	if err != nil {
		t.Fatalf("writeKiloCostPlugin: %v", err)
	}

	path := filepath.Join(dir, "plugin", kiloCostPluginName+".ts")
	if url != "file://"+path {
		t.Fatalf("url = %q, want file://%q", url, path)
	}
	body, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read the plugin: %v", err)
	}
	if len(body) == 0 {
		t.Fatal("the plugin is empty")
	}
	if !strings.Contains(string(body), "Generated by prizmal on launch") {
		t.Fatalf("the plugin carries no generated-file marker: %s", body)
	}
}

// A workaround outlives the person who wrote it unless it says why it exists and
// what ends it. The repository requires all three lines on every one.
func TestKiloCostPluginCarriesTheWorkaroundMarker(t *testing.T) {
	src := kiloCostPluginSource()
	for _, want := range []string{
		"UPSTREAM-WORKAROUND(kilo 7.8.18)",
		"evidence:",
		"remove-when:",
	} {
		if !strings.Contains(src, want) {
			t.Fatalf("the plugin has no %q line:\n%s", want, src)
		}
	}
}

// The rewrite has one job and three conditions on it. Each is asserted here so
// an edit that widens the blast radius fails the build rather than a real turn.
func TestKiloCostPluginGuards(t *testing.T) {
	src := kiloCostPluginSource()
	for _, want := range []string{
		// scope: only the prizmal base URL
		"isPrizmal",
		// only a numeric cost with no cost_details
		`typeof usage.cost !== "number"`,
		"usage.cost_details",
		// never fail a turn
		"catch",
	} {
		if !strings.Contains(src, want) {
			t.Fatalf("the plugin source lost the %q guard:\n%s", want, src)
		}
	}
	if strings.Contains(src, "throw") {
		t.Fatalf("the plugin throws, so a parse error would fail the turn:\n%s", src)
	}
}

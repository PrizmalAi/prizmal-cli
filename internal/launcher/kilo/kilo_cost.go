package kilo

import (
	"os"
	"path/filepath"
	"strings"
)

// UPSTREAM-WORKAROUND(kilo 7.8.18)
// evidence: Kilo never calls a plugin's auth.loader hook, and declaring one
// fails the launch with "Unexpected server error", so the charge cannot be
// delivered through a fetch that hook would return. Kilo reads
// usage.cost_details.upstream_inference_cost on the stream's usage frame and
// ignores usage.cost, which is the field the Switch sends.
// remove-when: Kilo reads the Switch's usage.cost natively, or auth.loader
// works, whichever comes first.
//
// The launch writes one TypeScript plugin into Kilo's own config directory and
// names it in the inline config. The plugin wraps globalThis.fetch and, on any
// server-sent frame carrying a numeric usage.cost and no cost_details, copies
// that value into usage.cost_details.upstream_inference_cost. Kilo then reports
// the Switch's real charge instead of zero.
//
// The plugin is an extra, not a precondition: a launch that cannot write it
// still runs, with the cost reading zero as before.
const (
	// kiloCostPluginName is the file's basename under dir/plugin.
	kiloCostPluginName = "prizmal_cost"

	// kiloCostBaseURLEnv carries the Switch base the wrapper scopes itself to.
	// It is read at call time, so nothing about the endpoint is baked into a
	// file on disk.
	kiloCostBaseURLEnv = "PRIZMAL_KILO_COST_BASE_URL"
)

// writeKiloCostPlugin generates the plugin under dir/plugin and returns the
// file URL the config names it by. It is rewritten on every launch so an older
// prizmal's version never lingers.
func writeKiloCostPlugin(dir string) (string, error) {
	pluginDir := filepath.Join(dir, "plugin")
	if err := os.MkdirAll(pluginDir, 0o755); err != nil {
		return "", err
	}
	path := filepath.Join(pluginDir, kiloCostPluginName+".ts")
	if err := os.WriteFile(path, []byte(kiloCostPluginSource()), 0o644); err != nil {
		return "", err
	}
	return "file://" + path, nil
}

// kiloCostPluginSource renders the plugin. Every substitution is an
// environment-variable name, never a value, so the generated file holds no
// endpoint and no credential.
func kiloCostPluginSource() string {
	return strings.NewReplacer("__BASE_URL_ENV__", kiloCostBaseURLEnv).Replace(kiloCostPluginTemplate)
}

const kiloCostPluginTemplate = `// Generated by prizmal on launch. Edits are overwritten.
//
// UPSTREAM-WORKAROUND(kilo 7.8.18)
// evidence: Kilo never calls a plugin's auth.loader hook, and declaring one fails
//   the launch with "Unexpected server error". Kilo reads
//   usage.cost_details.upstream_inference_cost and ignores usage.cost, which is
//   the field PrizmalSwitch sends on the usage frame.
// remove-when: Kilo reads the Switch's usage.cost natively, or auth.loader works.
//
// Copies the Switch's per-turn charge where Kilo looks for it. The wrapper
// touches only responses from the Prizmal base, only a frame that carries a
// numeric usage.cost and no cost_details, and never changes a frame it cannot
// parse: a turn that cannot be rewritten is delivered exactly as it arrived.

const BASE_URL = (process.env.__BASE_URL_ENV__ || "").replace(/\/+$/, "")
const originalFetch = globalThis.fetch

function requestURL(input) {
  try {
    if (typeof input === "string") return input
    if (input && typeof input.url === "string") return input.url
    return String(input)
  } catch {
    return ""
  }
}

// True only for the provider this launcher wrote into the config.
function isPrizmal(input) {
  if (!BASE_URL) return false
  const url = requestURL(input)
  if (!url) return false
  return url === BASE_URL || url.startsWith(BASE_URL + "/")
}

// One server-sent line in, one line out. Anything unrecognised is returned
// byte for byte.
function rewriteLine(line) {
  if (!line.startsWith("data:")) return line
  const payload = line.slice(5).trim()
  if (!payload || payload === "[DONE]") return line
  let frame
  try {
    frame = JSON.parse(payload)
  } catch {
    return line
  }
  const usage = frame && frame.usage
  if (!usage || typeof usage.cost !== "number" || usage.cost_details) return line
  usage.cost_details = { upstream_inference_cost: usage.cost }
  try {
    return "data: " + JSON.stringify(frame)
  } catch {
    return line
  }
}

async function wrappedFetch(input, init) {
  const response = await originalFetch(input, init)
  try {
    if (!isPrizmal(input) || !response.ok || !response.body) return response
    const type = response.headers.get("content-type") || ""
    if (!type.includes("text/event-stream")) return response

    const reader = response.body.getReader()
    const decoder = new TextDecoder()
    const encoder = new TextEncoder()
    let carry = ""

    const body = new ReadableStream({
      async pull(controller) {
        let chunk
        try {
          chunk = await reader.read()
        } catch (err) {
          controller.error(err)
          return
        }
        if (chunk.done) {
          if (carry) controller.enqueue(encoder.encode(rewriteLine(carry)))
          controller.close()
          return
        }
        let text = ""
        try {
          text = decoder.decode(chunk.value, { stream: true })
        } catch {
          text = ""
        }
        const lines = (carry + text).split("\n")
        // The last element is an unfinished line; hold it until the next chunk.
        carry = lines.pop() || ""
        controller.enqueue(encoder.encode(lines.map(rewriteLine).join("\n") + (lines.length ? "\n" : "")))
      },
    })
    return new Response(body, {
      status: response.status,
      statusText: response.statusText,
      headers: response.headers,
    })
  } catch {
    // A wrapper that cannot do its job must not cost the turn.
    return response
  }
}

globalThis.fetch = wrappedFetch

export const PrizmalCostPlugin = async () => ({})
`

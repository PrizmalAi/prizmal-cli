package opencode

import (
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"

	"github.com/PrizmalAi/prizmal-cli/internal/envconfig"
)

// A device token expires ten minutes after issue, and opencode reads a static
// apiKey once. Its `chat.headers` plugin hook runs before every model request
// and can await a command, so a device-mode launch hands opencode a plugin
// whose hook runs `prizmal auth token` and sets the Authorization header from
// what it prints. The helper reuses a cached token until it nears expiry, so
// most requests cost one cheap subprocess and none holds a key on disk.
//
// Like the search tool, the plugin lives in the prizmal-owned directory that
// OPENCODE_CONFIG_DIR names, which opencode globs for `{plugin,plugins}/*.{js,ts}`.
const (
	openCodeAuthPluginFile = "prizmal_auth.ts"

	// openCodeAuthBinEnv names the prizmal executable the plugin runs, so a
	// prizmal started by path still finds itself when it is not on PATH.
	openCodeAuthBinEnv = "PRIZMAL_OPENCODE_AUTH_BIN"
)

// prepareAuthPlugin is the only place the auth plugin is written or removed,
// and Run calls it before the launch environment is built. A device-mode launch
// has no key in its config, so the plugin is its credential and a launch that
// cannot write it fails here rather than start a session every request of which
// would be refused. Any other launch removes a plugin an earlier device launch
// left behind, so a static-key launch never runs the command.
func prepareAuthPlugin() error {
	dir, err := openCodeSearchDir()
	deviceAuth := envconfig.DeviceMode() && !envconfig.RelayMode()
	if err != nil {
		if deviceAuth {
			return fmt.Errorf("find the directory for OpenCode's auth plugin: %w", err)
		}
		return nil
	}
	err = syncOpenCodeAuthPlugin(dir, deviceAuth)
	if err != nil && deviceAuth {
		return fmt.Errorf("write OpenCode's auth plugin: %w", err)
	}
	// A plugin that cannot be removed on a static-key launch is not a reason to
	// stop it, as before.
	return nil
}

// syncOpenCodeAuthPlugin makes dir match the launch: the plugin is written on a
// device-mode launch and removed on any other, so a static-key launch never
// runs the command.
func syncOpenCodeAuthPlugin(dir string, deviceMode bool) error {
	if deviceMode {
		return writeOpenCodeAuthPlugin(dir)
	}
	err := os.Remove(filepath.Join(dir, "plugin", openCodeAuthPluginFile))
	if err != nil && !errors.Is(err, fs.ErrNotExist) {
		return err
	}
	return nil
}

// writeOpenCodeAuthPlugin generates the plugin under dir/plugin. It is
// rewritten on every launch so an older prizmal's version never lingers.
func writeOpenCodeAuthPlugin(dir string) error {
	pluginDir := filepath.Join(dir, "plugin")
	if err := os.MkdirAll(pluginDir, 0o755); err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(pluginDir, openCodeAuthPluginFile), []byte(openCodeAuthPluginSource()), 0o644)
}

// openCodeAuthPluginSource renders the plugin module. opencode swallows an
// exception from a hook and sends the request with no credential, so the hook
// never relies on one: a failed or empty command leaves no header, and the
// Switch's 401 is what the operator sees.
func openCodeAuthPluginSource() string {
	return `// Generated by prizmal on launch. Edits are overwritten.
//
// Sets the Authorization header from ` + "`prizmal auth token`" + ` before every request, so a
// session that outlives one device token keeps working.
export const PrizmalAuth = async ({ $ }) => ({
  "chat.headers": async (input, output) => {
    if (input.model.providerID !== "prizmal") return
    let token = ""
    try {
      const bin = process.env.` + openCodeAuthBinEnv + ` || "prizmal"
      const result = await $` + "`${bin} auth token`" + `.quiet().nothrow()
      if (result.exitCode === 0) token = result.stdout.toString().trim()
    } catch {}
    if (token) output.headers["Authorization"] = "Bearer " + token
  },
})
`
}
